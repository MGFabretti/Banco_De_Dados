CREATE TABLE IF NOT EXISTS PRODUTO(
	PRO_ID				INT AUTO_INCREMENT PRIMARY KEY,
    PRO_NOME 			VARCHAR(50) NOT NULL,
    PRO_DESCRICAO 		VARCHAR(255),
    PRO_PRECO  			DOUBLE NOT NULL,
    PRO_QTD_DISPONIVEL 	INT NOT NULL
);

CREATE TABLE IF NOT EXISTS ALUGUEL(
	ALU_ID 				INT AUTO_INCREMENT PRIMARY KEY,
    ALU_DATA_ALUGUEL 	DATE NOT NULL,
    ALU_DATA_EVOLUCAO 	DATE NOT NULL,
    ALU_VALOR_TOTAL  	DOUBLE NOT NULL,
    FK_CLIENTE_CLI_ID 	INT,
	FOREIGN KEY (FK_CLIENTE_CLI_ID) REFERENCES CLIENTE(CLI_ID)
);

CREATE TABLE IF NOT EXISTS ALUGUEL_PRODUTO(
	ALP_ID 					INT AUTO_INCREMENT PRIMARY KEY,
	FK_PRODUTO_PRO_ID 		INT NOT NULL,
    FK_ALUGUEL_ALU_ID 		INT NOT NULL,
    FOREIGN KEY (FK_PRODUTO_PRO_ID) REFERENCES PRODUTO(PRO_ID),
    FOREIGN KEY (FK_ALUGUEL_ALU_ID) REFERENCES ALUGUEL(ALU_ID)
);

